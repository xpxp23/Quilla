interface ThemeStudioState {
  activePresetId: string;
  currentConfig: TypographyPreset;
  customPresets: TypographyPreset[];
}

function loadStudioState(): ThemeStudioState {
  const defaultPreset = { ...BUILTIN_TYPOGRAPHY_PRESETS[0] };
  if (typeof localStorage === "undefined") {
    return {
      activePresetId: defaultPreset.id,
      currentConfig: defaultPreset,
      customPresets: [],
    };
  }
  try {
    const raw = localStorage.getItem(STUDIO_STORAGE_KEY);
    if (!raw) {
      return {
        activePresetId: defaultPreset.id,
        currentConfig: defaultPreset,
        customPresets: [],
      };
    }
    const parsed = JSON.parse(raw);
    return {
      activePresetId: parsed.activePresetId || defaultPreset.id,
      currentConfig: { ...defaultPreset, ...(parsed.currentConfig || {}) },
      customPresets: Array.isArray(parsed.customPresets) ? parsed.customPresets : [],
    };
  } catch {
    return {
      activePresetId: defaultPreset.id,
      currentConfig: defaultPreset,
      customPresets: [],
    };
  }
}

let studioState: ThemeStudioState = loadStudioState();

function persistStudioState() {
  if (typeof localStorage === "undefined") return;
  try {
    localStorage.setItem(STUDIO_STORAGE_KEY, JSON.stringify(studioState));
  } catch {
    // ignore
  }
}

export function getActiveThemeStudioPreset(): TypographyPreset {
  return studioState.currentConfig;
}

export function getAllTypographyPresets(): TypographyPreset[] {
  return [...BUILTIN_TYPOGRAPHY_PRESETS, ...studioState.customPresets];
}

export function applyThemeStudioToDOM(preset: TypographyPreset = studioState.currentConfig) {
  if (typeof document === "undefined") return;
  const root = document.documentElement;
  const baseFontSize = getPreferences().fontSize || 15;
  const scaledPx = Math.round(baseFontSize * preset.fontSizeScale * 10) / 10;

  root.style.setProperty("--editor-font-size", `${scaledPx}px`);
  root.style.setProperty("--editor-line-height", String(preset.lineHeight));
  root.style.setProperty("--paragraph-spacing", `${preset.paragraphSpacingEm}em`);
  root.style.setProperty("--primary-color", preset.primaryAccentColor);
  root.style.setProperty("--quote-border-color", preset.quoteBorderColor);
  root.dataset.codeCardStyle = preset.codeCardStyle;
  root.dataset.tableDensity = preset.tableDensity;
}

export function updateActiveThemeStudioConfig(partial: Partial<TypographyPreset>) {
  studioState.currentConfig = {
    ...studioState.currentConfig,
    ...partial,
  };
  persistStudioState();
  applyThemeStudioToDOM(studioState.currentConfig);
}

export function saveCustomTypographyPreset(name: string): TypographyPreset {
  const cleanName = name.trim() || `自定义模板 ${studioState.customPresets.length + 1}`;
  const id = `custom-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`;
  const newPreset: TypographyPreset = {
    ...studioState.currentConfig,
    id,
    name: cleanName,
    isBuiltIn: false,
  };
  studioState.customPresets.push(newPreset);
  studioState.activePresetId = id;
  studioState.currentConfig = { ...newPreset };
  persistStudioState();
  applyThemeStudioToDOM(studioState.currentConfig);
  return newPreset;
}

export function selectTypographyPresetById(id: string): TypographyPreset {
  const all = getAllTypographyPresets();
  const found = all.find((p) => p.id === id) || BUILTIN_TYPOGRAPHY_PRESETS[0];
  studioState.activePresetId = found.id;
  studioState.currentConfig = { ...found };
  persistStudioState();
  applyThemeStudioToDOM(studioState.currentConfig);
  updatePreferences({ lineHeight: found.lineHeight });
  return studioState.currentConfig;
}

export function deleteCustomTypographyPreset(id: string): boolean {
  const beforeLen = studioState.customPresets.length;
  studioState.customPresets = studioState.customPresets.filter((p) => p.id !== id);
  if (studioState.customPresets.length === beforeLen) return false;
  if (studioState.activePresetId === id) {
    selectTypographyPresetById(BUILTIN_TYPOGRAPHY_PRESETS[0].id);
  } else {
    persistStudioState();
  }
  return true;
}

/**
 * 构建注入到导出文档（PDF / 长图 / HTML）的 CSS 自定义变量覆盖块
 */
export function buildThemeStudioExportVariablesCss(
  preset: TypographyPreset = studioState.currentConfig
): string {
  return `
    :root {
      --primary-color: ${preset.primaryAccentColor};
      --quote-border-color: ${preset.quoteBorderColor};
      --paragraph-spacing: ${preset.paragraphSpacingEm}em;
      --editor-line-height: ${preset.lineHeight};
      --theme-studio-font-scale: ${preset.fontSizeScale};
    }
    p {
      margin: ${preset.paragraphSpacingEm}em 0;
      line-height: ${preset.lineHeight};
    }
    h1, h2 {
      border-color: ${preset.primaryAccentColor};
    }
    blockquote {
      border-left-color: ${preset.quoteBorderColor};
    }
    ${
      preset.codeCardStyle === "minimal"
        ? `.exported-code-dots { display: none !important; }`
        : ""
    }
  `;
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

